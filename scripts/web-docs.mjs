#!/usr/bin/env node
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SRC_DIR = join(ROOT, "docs", "features", "web");
const OUT = join(ROOT, "apps", "web", "src", "lib", "webDocs.ts");

const DOC_SECTIONS = [
  "Start here", "How ADCode works", "Earning and advertising", "Comparisons",
  "Editing", "Finding your way", "Formatting", "Understanding a project",
  "Languages", "The assistant", "Git", "Your session", "The workbench",
  "Appearance", "Account", "Files and gestures", "Ads and earnings", "Updates",
];

const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

function parseFrontMatter(source, file) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source);
  if (match === null) throw new Error(`${file}: missing front matter delimited by ---`);
  const meta = {};
  for (const line of match[1].split("\n")) {
    if (line.trim() === "") continue;
    const pair = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
    if (pair === null) throw new Error(`${file}: bad front matter line: ${line}`);
    const key = pair[1];
    let value = pair[2].trim();
    if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1);
    if (key === "order") meta[key] = Number(value);
    else if (key === "related") meta[key] = value === "" ? [] : value.split(/\s*,\s*/).filter(Boolean);
    else meta[key] = value;
  }
  return { meta, body: match[2].replace(/^\n+/, "").replace(/\n+$/, "\n") };
}

const files = readdirSync(SRC_DIR).filter((name) => name.endsWith(".md")).sort();
if (files.length === 0) throw new Error(`no markdown docs in ${SRC_DIR}`);

const docs = [];
const slugs = new Set();
for (const file of files) {
  const source = read(join(SRC_DIR, file));
  const { meta, body } = parseFrontMatter(source, file);
  for (const required of ["slug", "title", "description", "section", "published"]) {
    if (typeof meta[required] !== "string" || meta[required].trim() === "") {
      throw new Error(`${file}: missing required field "${required}"`);
    }
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.published)) throw new Error(`${file}: published must be YYYY-MM-DD`);
  if (meta.updated !== undefined && !/^\d{4}-\d{2}-\d{2}$/.test(meta.updated)) throw new Error(`${file}: updated must be YYYY-MM-DD`);
  if (!DOC_SECTIONS.includes(meta.section)) throw new Error(`${file}: unknown section "${meta.section}"`);
  if (slugs.has(meta.slug)) throw new Error(`${file}: duplicate slug "${meta.slug}"`);
  slugs.add(meta.slug);
  if (body.trim().length < 200) throw new Error(`${file}: body too short`);
  docs.push({
    slug: meta.slug,
    title: meta.title,
    description: meta.description,
    section: meta.section,
    published: meta.published,
    ...(meta.updated === undefined ? {} : { updated: meta.updated }),
    ...(meta.order === undefined ? {} : { order: meta.order }),
    related: Array.isArray(meta.related) ? meta.related : [],
    body,
  });
}

docs.sort((a, b) => a.slug.localeCompare(b.slug));

const rawOutput = `/**
 * Authored web documentation.
 *
 * GENERATED by \`node scripts/web-docs.mjs\` from \`docs/features/web/*.md\`. Do not edit
 * this file by hand; edit the Markdown and regenerate. Run \`node scripts/web-docs.mjs --check\`
 * to confirm the committed copy is current.
 */

export interface WebDoc {
  readonly slug: string;
  readonly title: string;
  readonly description: string;
  readonly section: string;
  readonly published: string;
  readonly updated?: string;
  readonly order?: number;
  readonly related: string[];
  readonly body: string;
}

export const WEB_DOCS: readonly WebDoc[] = [
${docs
  .map(
    (doc) => `  {
    slug: ${JSON.stringify(doc.slug)},
    title: ${JSON.stringify(doc.title)},
    description: ${JSON.stringify(doc.description)},
    section: ${JSON.stringify(doc.section)},
    published: ${JSON.stringify(doc.published)},
    ${doc.updated === undefined ? "" : `updated: ${JSON.stringify(doc.updated)},\n    `}
    ${doc.order === undefined ? "" : `order: ${doc.order},\n    `}
    related: ${JSON.stringify(doc.related)},
    body: ${JSON.stringify(doc.body)},
  },`,
  )
  .join("\n")}
];
`;

const output = rawOutput.replace(/[ \t]+$/gm, "");

if (process.argv.includes("--check")) {
  const current = read(OUT);
  if (current !== output) {
    console.error("webDocs.ts is stale. Run: node scripts/web-docs.mjs");
    process.exit(1);
  }
  console.log("webDocs.ts is up to date.");
} else {
  writeFileSync(OUT, output, "utf8");
  console.log(`Wrote ${docs.length} docs to ${OUT}`);
}
