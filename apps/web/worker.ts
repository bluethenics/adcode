/**
 * The Worker's entry point: the one OpenNext generates, with the site's videos in front.
 *
 * `/videos/*` reaches the Worker before the asset server (`assets.run_worker_first` in
 * wrangler.jsonc) so that a `Range` request gets `206 Partial Content`, which Safari needs
 * to play a video at all - see `src/lib/byteRange.ts`. Everything else is OpenNext's.
 *
 * Left out of tsconfig.json: type-checking this file pulls in the whole generated server
 * through the import below. The logic worth checking is in `byteRange.ts`, which is.
 */
import { runScheduledMailing, runScheduledStatus } from "./src/lib/mailing";
// @ts-ignore - generated by the Cloudflare build, absent on a fresh checkout.
import openNext from "./.open-next/worker.js";
import { serveWithRanges, type AssetFetcher } from "./src/lib/byteRange";
import { withClientCancellation } from "./src/lib/clientCancellation";

export default {
  /*
   * Every quarter hour: the status watcher and its alerts, so "a model is failing" arrives within
   * minutes. The return campaign and announcements keep their hourly pace, on the hour's tick.
   */
  async scheduled(controller: { scheduledTime: number }): Promise<void> {
    const status = await runScheduledStatus(controller.scheduledTime);
    console.info("ADCode status alerts", status);
    if (new Date(controller.scheduledTime).getUTCMinutes() < 15) {
      const result = await runScheduledMailing();
      console.info("ADCode mailing", result);
    }
  },
  async fetch(request: Request, env: { ASSETS: AssetFetcher }, ctx: unknown): Promise<Response> {
    if (new URL(request.url).pathname.startsWith("/videos/")) return serveWithRanges(request, env.ASSETS);
    return withClientCancellation(request, () => openNext.fetch(request, env, ctx));
  },
};
