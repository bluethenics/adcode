/**
 * Other tools' conversations, read into ADCode's own shape.
 *
 * Somebody arriving from Claude Code, Codex or OpenCode has months of context in those
 * tools' session files, and starting again from nothing is a reason not to switch. Each
 * parser here takes one tool's file as text and returns the conversation as it was said:
 * the person's messages and the assistant's replies, in order. Tool calls, tool output,
 * reasoning, system prompts and injected context are left behind - they are not the
 * conversation, they are large, and they are the part most likely to hold a secret.
 *
 * Also read: the files those products export (claude.ai and ChatGPT `conversations.json`),
 * and ADCode's own JSON export, so a conversation can move between machines.
 *
 * Pure: text in, data out. Reading disks belongs to `chatImport.ts`.
 */
import type { ChatMessage, ChatSession } from "@adcode/ai";

export type ChatImportSource = "claude-code" | "codex" | "opencode" | "claude-export" | "chatgpt-export" | "adcode-export";

export const CHAT_IMPORT_SOURCES: Readonly<Record<ChatImportSource, string>> = {
  "claude-code": "Claude Code",
  codex: "Codex",
  opencode: "OpenCode",
  "claude-export": "Claude (exported file)",
  "chatgpt-export": "ChatGPT (exported file)",
  "adcode-export": "ADCode (exported file)",
};

export interface ImportedChat {
  readonly source: ChatImportSource;
  /** The tool's own id for the conversation; with the source, what makes a re-import replace rather than duplicate. */
  readonly sourceId: string;
  readonly title: string;
  /** The project folder the conversation happened in, when the tool recorded one. */
  readonly cwd: string | null;
  readonly startedAt: number;
  readonly updatedAt: number;
  readonly messages: readonly ChatMessage[];
}

const MAX_MESSAGES = 600;
const MAX_MESSAGE_CHARS = 40_000;
const MAX_TITLE = 80;

type Json = Record<string, unknown>;
const object = (value: unknown): Json | null => (typeof value === "object" && value !== null && !Array.isArray(value) ? (value as Json) : null);
const text = (value: unknown): string => (typeof value === "string" ? value : "");

function time(value: unknown): number {
  if (typeof value === "number" && Number.isFinite(value)) return value > 1e12 ? value : value > 1e9 ? value * 1000 : 0;
  if (typeof value === "string") {
    const parsed = Date.parse(value);
    return Number.isFinite(parsed) ? parsed : 0;
  }
  return 0;
}

function lines(file: string): Json[] {
  const out: Json[] = [];
  for (const line of file.split("\n")) {
    if (line.length < 2) continue;
    try {
      const parsed = object(JSON.parse(line));
      if (parsed !== null) out.push(parsed);
    } catch {
      // A line cut off mid-write costs that line.
    }
  }
  return out;
}

/**
 * Text a tool injected rather than a person typed: environment blocks, command wrappers,
 * reminders. They arrive in the user role, and importing them would put somebody else's
 * prompt engineering into the transcript as if the person had said it.
 */
export function isInjectedText(value: string): boolean {
  const start = value.trimStart();
  return /^<(environment_context|user_instructions|system-reminder|command-name|command-message|local-command-stdout|local-command-caveat|task-notification|permissions|turn_aborted|user_shell_command)\b/i.test(start)
    || start.startsWith("Caveat: The messages below were generated by the user while running local commands")
    || start.startsWith("[Request interrupted");
}

function titleOf(explicit: string, messages: readonly ChatMessage[]): string {
  const base = explicit.trim() !== "" ? explicit : messages.find((message) => message.role === "user")?.text ?? "Imported conversation";
  const line = base.replace(/\s+/g, " ").trim();
  return line.length > MAX_TITLE ? `${line.slice(0, MAX_TITLE - 1).trimEnd()}…` : line || "Imported conversation";
}

/** Order kept, empties dropped, each message and the whole list held to a size the chat can show. */
function finish(source: ChatImportSource, sourceId: string, title: string, cwd: string | null, raw: readonly ChatMessage[]): ImportedChat | null {
  const merged: ChatMessage[] = [];
  for (const message of raw) {
    const body = message.text.trim();
    if (body === "") continue;
    const clipped = body.length > MAX_MESSAGE_CHARS ? `${body.slice(0, MAX_MESSAGE_CHARS)}\n\n[Shortened on import]` : body;
    const last = merged[merged.length - 1];
    // A tool splits one reply into several blocks around its tool calls; here it is one reply.
    if (last !== undefined && last.role === "assistant" && message.role === "assistant") {
      merged[merged.length - 1] = { ...last, text: `${last.text}\n\n${clipped}`.slice(0, MAX_MESSAGE_CHARS) };
    } else merged.push({ role: message.role, text: clipped, at: message.at });
  }
  if (sourceId === "" || !merged.some((message) => message.role === "user")) return null;
  const kept = merged.slice(-MAX_MESSAGES);
  const times = kept.map((message) => message.at).filter((at) => at > 0);
  return {
    source, sourceId, cwd: cwd !== null && cwd.trim() !== "" ? cwd : null,
    title: titleOf(title, kept),
    startedAt: times.length > 0 ? Math.min(...times) : 0,
    updatedAt: times.length > 0 ? Math.max(...times) : 0,
    messages: kept,
  };
}

/** The text blocks of an Anthropic- or OpenAI-style content value; nothing else in it is conversation. */
function contentText(content: unknown, kinds: readonly string[]): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content.map((block) => {
    const item = object(block);
    return item !== null && kinds.includes(text(item["type"])) ? text(item["text"]) : "";
  }).filter((part) => part !== "").join("\n\n");
}

/** One `~/.claude/projects/<folder>/<session>.jsonl`. Sub-agent turns are not the conversation. */
export function parseClaudeCodeSession(file: string, fallbackId: string): ImportedChat | null {
  const messages: ChatMessage[] = [];
  let id = "";
  let cwd: string | null = null;
  let title = "";
  for (const entry of lines(file)) {
    const type = text(entry["type"]);
    if (id === "") id = text(entry["sessionId"]);
    if (type === "custom-title") title = text(entry["customTitle"]);
    else if (type === "summary" && title === "") title = text(entry["summary"]);
    if ((type !== "user" && type !== "assistant") || entry["isSidechain"] === true || entry["isMeta"] === true) continue;
    if (cwd === null && text(entry["cwd"]) !== "") cwd = text(entry["cwd"]);
    const body = contentText(object(entry["message"])?.["content"], ["text"]);
    if (body.trim() === "" || (type === "user" && isInjectedText(body))) continue;
    messages.push({ role: type, text: body, at: time(entry["timestamp"]) });
  }
  return finish("claude-code", id || fallbackId, title, cwd, messages);
}

/** One `~/.codex/sessions/…/rollout-*.jsonl`. Developer messages are the tool's own instructions. */
export function parseCodexSession(file: string, fallbackId: string): ImportedChat | null {
  const messages: ChatMessage[] = [];
  let id = "";
  let cwd: string | null = null;
  for (const entry of lines(file)) {
    const payload = object(entry["payload"]);
    if (payload === null) continue;
    if (entry["type"] === "session_meta") {
      id = text(payload["id"]) || text(payload["session_id"]);
      cwd = text(payload["cwd"]) || null;
      continue;
    }
    if (entry["type"] !== "response_item" || payload["type"] !== "message") continue;
    const role = payload["role"];
    if (role !== "user" && role !== "assistant") continue;
    const body = contentText(payload["content"], role === "user" ? ["input_text"] : ["output_text"]);
    if (body.trim() === "" || (role === "user" && isInjectedText(body))) continue;
    messages.push({ role, text: body, at: time(entry["timestamp"]) });
  }
  return finish("codex", id || fallbackId, "", cwd, messages);
}

/** OpenCode keeps a session, its messages and their parts in separate files; the reader joins them. */
export interface OpenCodeMessage { readonly role: string; readonly at: number; readonly parts: readonly string[] }
export function buildOpenCodeSession(info: unknown, entries: readonly OpenCodeMessage[]): ImportedChat | null {
  const record = object(info);
  if (record === null) return null;
  const messages: ChatMessage[] = [];
  for (const entry of [...entries].sort((a, b) => a.at - b.at)) {
    if (entry.role !== "user" && entry.role !== "assistant") continue;
    const body = entry.parts.join("\n\n");
    if (entry.role === "user" && isInjectedText(body)) continue;
    messages.push({ role: entry.role, text: body, at: entry.at });
  }
  return finish("opencode", text(record["id"]), text(record["title"]), text(record["directory"]) || null, messages);
}

/** The text of one OpenCode part file, or "" for anything that is not the person's or the model's words. */
export function openCodePartText(part: unknown): string {
  const record = object(part);
  return record !== null && record["type"] === "text" && record["synthetic"] !== true ? text(record["text"]) : "";
}

function claudeExport(conversation: Json): ImportedChat | null {
  const messages: ChatMessage[] = [];
  for (const raw of Array.isArray(conversation["chat_messages"]) ? conversation["chat_messages"] : []) {
    const message = object(raw);
    if (message === null) continue;
    const sender = message["sender"];
    const body = text(message["text"]) || contentText(message["content"], ["text"]);
    if (sender !== "human" && sender !== "assistant") continue;
    messages.push({ role: sender === "human" ? "user" : "assistant", text: body, at: time(message["created_at"]) });
  }
  return finish("claude-export", text(conversation["uuid"]), text(conversation["name"]), null, messages);
}

function chatgptExport(conversation: Json): ImportedChat | null {
  const mapping = object(conversation["mapping"]);
  if (mapping === null) return null;
  // The export is a tree of every edit and regeneration; the conversation is the branch that ends at `current_node`.
  const branch: Json[] = [];
  let cursor = text(conversation["current_node"]);
  for (let guard = 0; cursor !== "" && guard < 5000; guard += 1) {
    const node = object(mapping[cursor]);
    if (node === null) break;
    branch.push(node);
    cursor = text(node["parent"]);
  }
  const messages: ChatMessage[] = [];
  for (const node of branch.reverse()) {
    const message = object(node["message"]);
    const role = object(message?.["author"])?.["role"];
    if (message === null || (role !== "user" && role !== "assistant")) continue;
    const content = object(message["content"]);
    if (content === null || content["content_type"] !== "text") continue;
    const body = (Array.isArray(content["parts"]) ? content["parts"] : []).filter((part): part is string => typeof part === "string").join("\n\n");
    messages.push({ role, text: body, at: time(message["create_time"]) });
  }
  return finish("chatgpt-export", text(conversation["conversation_id"]) || text(conversation["id"]), text(conversation["title"]), null, messages);
}

/**
 * A file somebody chose: ADCode's own export, or a `conversations.json` from claude.ai or
 * ChatGPT. Returns the conversations found, and an empty list for anything else.
 */
export function parseExportFile(json: unknown, limit = 500): ImportedChat[] {
  const single = object(json);
  if (single !== null && single["format"] === "adcode-conversation") {
    const messages: ChatMessage[] = [];
    for (const raw of Array.isArray(single["messages"]) ? single["messages"] : []) {
      const message = object(raw);
      const role = message?.["role"];
      if (message !== null && (role === "user" || role === "assistant")) messages.push({ role, text: text(message["text"]), at: time(single["exportedAt"]) });
    }
    const title = text(single["title"]);
    const chat = finish("adcode-export", `${title}:${text(single["exportedAt"])}`, title, null, messages);
    return chat === null ? [] : [chat];
  }
  if (!Array.isArray(json)) return [];
  const out: ImportedChat[] = [];
  for (const raw of json) {
    const conversation = object(raw);
    if (conversation === null) continue;
    const chat = conversation["mapping"] !== undefined ? chatgptExport(conversation) : conversation["chat_messages"] !== undefined ? claudeExport(conversation) : null;
    if (chat !== null) out.push(chat);
    if (out.length >= limit) break;
  }
  return out;
}

/**
 * The conversation as an ADCode session. `id` is derived from where it came from, by the
 * caller, so importing the same conversation twice replaces it instead of listing it twice.
 * The title says where it came from, because an imported chat's replies were not ADCode's.
 */
export function importedSession(chat: ImportedChat, id: string, now: number): ChatSession {
  return {
    id,
    title: chat.title,
    // Renamed, so auto-titling never overwrites the title the other tool gave it.
    renamed: true,
    createdAt: chat.startedAt > 0 ? chat.startedAt : now,
    updatedAt: chat.updatedAt > 0 ? chat.updatedAt : now,
    messages: chat.messages,
    summary: null,
  };
}
