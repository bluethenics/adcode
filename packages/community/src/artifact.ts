/**
 * Project artifacts: a project published so other ADCode users can remix it and send back
 * improvements.
 *
 * The flow is a pull request without Git: the owner publishes a snapshot (version 1), anyone
 * remixes it into a folder of their own, works on it with their own AI, and sends an
 * improvement - the changes between the version they started from and what they have now.
 * The owner reads it file by file and accepts or declines; an accepted improvement becomes
 * the next version, with its author credited.
 *
 * Everything here is pure so the desktop app and the server decide the same things: which
 * files may be published, whether a file is hiding a key, what changed, and whether a
 * change still applies to the version that has moved on since.
 */

export interface ArtifactFile {
  /** Forward-slash path relative to the project root. */
  readonly path: string;
  readonly content: string;
}

export type ChangeKind = "added" | "modified" | "deleted";

export interface ArtifactChange {
  readonly path: string;
  readonly kind: ChangeKind;
  /** The content the change was made against; null for an added file. */
  readonly before: string | null;
  /** The content it leaves; null for a deleted file. */
  readonly after: string | null;
}

export const ARTIFACT_LIMITS = {
  files: 400,
  bytes: 2_000_000,
  fileBytes: 200_000,
  changeBytes: 1_000_000,
  changes: 200,
} as const;

/** Folders that are generated, installed or private - never part of what somebody shares. */
const SKIPPED_FOLDERS = new Set([
  "node_modules", ".git", ".hg", ".svn", "dist", "build", "out", ".next", ".nuxt", ".svelte-kit", ".turbo",
  ".vercel", ".netlify", ".open-next", ".wrangler", "coverage", ".cache", ".parcel-cache", "__pycache__",
  ".venv", "venv", "env", ".tox", ".mypy_cache", ".pytest_cache", "target", "bin", "obj", ".gradle",
  ".idea", ".vscode", ".adcode", ".claude", ".codex", ".agents", "vendor", "Pods", ".dart_tool",
]);

/** Files that are private by name, whatever is in them. */
const PRIVATE_FILES = [/^\.env(?:\..*)?$/i, /^\.npmrc$/i, /^\.pypirc$/i, /^id_(?:rsa|ed25519|ecdsa)/i, /\.(?:pem|key|p12|pfx|keystore|jks)$/i, /^credentials(?:\.json)?$/i, /^service-account.*\.json$/i, /^\.netrc$/i];

/** Text the app can show and diff. Binary files (images, fonts, archives) stay out of v1 artifacts. */
const TEXT_EXTENSIONS = new Set([
  "html", "htm", "css", "scss", "sass", "less", "js", "mjs", "cjs", "jsx", "ts", "tsx", "mts", "cts", "json", "jsonc",
  "md", "mdx", "txt", "svg", "xml", "yml", "yaml", "toml", "ini", "cfg", "conf", "csv", "tsv", "vue", "svelte", "astro",
  "py", "rb", "go", "rs", "java", "kt", "kts", "swift", "c", "h", "cc", "cpp", "hpp", "cs", "php", "lua", "dart",
  "sh", "bash", "zsh", "ps1", "bat", "sql", "graphql", "gql", "prisma", "r", "ex", "exs", "erl", "hs", "scala",
  "clj", "elm", "ml", "fs", "zig", "nim", "sol", "tf", "hcl", "gradle", "properties", "lock", "gitignore", "editorconfig",
]);
const TEXT_NAMES = new Set(["Dockerfile", "Makefile", "Procfile", "LICENSE", "README", "Gemfile", "Rakefile", ".gitignore", ".editorconfig", ".prettierrc", ".eslintrc", ".nvmrc"]);
/** Lockfiles are enormous and regenerated by an install; a remix runs the install instead. */
const LOCKFILES = new Set(["package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "Cargo.lock", "poetry.lock", "composer.lock", "Gemfile.lock"]);

export type FileVerdict = { readonly include: true } | { readonly include: false; readonly reason: "folder" | "private" | "binary" | "large" | "lockfile" | "path" };

/** Whether a file found while walking a project belongs in its artifact. */
export function artifactFileVerdict(path: string, bytes: number): FileVerdict {
  if (!isSafeArtifactPath(path)) return { include: false, reason: "path" };
  const parts = path.split("/");
  if (parts.slice(0, -1).some((part) => SKIPPED_FOLDERS.has(part))) return { include: false, reason: "folder" };
  const name = parts[parts.length - 1]!;
  if (PRIVATE_FILES.some((pattern) => pattern.test(name))) return { include: false, reason: "private" };
  if (LOCKFILES.has(name)) return { include: false, reason: "lockfile" };
  const extension = name.includes(".") ? name.slice(name.lastIndexOf(".") + 1).toLowerCase() : "";
  if (!TEXT_NAMES.has(name) && !TEXT_EXTENSIONS.has(extension) && !(name.startsWith(".") && !name.slice(1).includes("."))) return { include: false, reason: "binary" };
  if (bytes > ARTIFACT_LIMITS.fileBytes) return { include: false, reason: "large" };
  return { include: true };
}

/** Whether a folder is worth descending into while collecting files. */
export const artifactFolderAllowed = (name: string): boolean => !SKIPPED_FOLDERS.has(name);

/**
 * A relative path that cannot escape the folder it is written into.
 *
 * Checked on publish, on remix and on every accepted change, because a path is the one
 * field of an artifact that turns into a file write on somebody else's disk.
 */
export function isSafeArtifactPath(path: string): boolean {
  if (typeof path !== "string" || path.length === 0 || path.length > 240) return false;
  if (path.startsWith("/") || path.includes("\\") || /^[a-zA-Z]:/.test(path) || path.includes("\0")) return false;
  const parts = path.split("/");
  return parts.every((part) => part.length > 0 && part !== "." && part !== ".." && !/[<>:"|?*\u0000-\u001f]/.test(part) && !/^(?:con|prn|aux|nul|com\d|lpt\d)(?:\..*)?$/i.test(part) && !/[. ]$/.test(part));
}

export interface SecretFinding {
  readonly path: string;
  readonly line: number;
  readonly kind: string;
}

const SECRET_PATTERNS: readonly { readonly kind: string; readonly pattern: RegExp }[] = [
  { kind: "private key", pattern: /-----BEGIN (?:RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY-----/ },
  { kind: "OpenAI or Anthropic key", pattern: /\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{24,}/ },
  { kind: "AWS access key", pattern: /\b(?:AKIA|ASIA)[0-9A-Z]{16}\b/ },
  { kind: "GitHub token", pattern: /\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36,}\b|\bgithub_pat_[A-Za-z0-9_]{60,}\b/ },
  { kind: "Google API key", pattern: /\bAIza[0-9A-Za-z_-]{35}\b/ },
  { kind: "Slack token", pattern: /\bxox[abpors]-[A-Za-z0-9-]{10,}/ },
  { kind: "Stripe secret key", pattern: /\b(?:sk|rk)_live_[A-Za-z0-9]{20,}/ },
  { kind: "database URL with a password", pattern: /\b(?:postgres(?:ql)?|mysql|mongodb(?:\+srv)?|redis):\/\/[^\s:/@]+:[^\s@/]{6,}@/ },
];

/**
 * Keys and passwords sitting in files about to be made public.
 *
 * A published artifact is readable by anyone, forever in somebody's remix, so a finding
 * blocks publishing outright - there is no "publish anyway". The fix is to move the value
 * into `.env`, which is never published.
 */
export function findSecrets(files: readonly ArtifactFile[]): SecretFinding[] {
  const findings: SecretFinding[] = [];
  for (const file of files) {
    const lines = file.content.split("\n");
    for (let index = 0; index < lines.length && findings.length < 50; index++) {
      const line = lines[index]!;
      if (line.length > 4000) continue;
      for (const { kind, pattern } of SECRET_PATTERNS) {
        if (pattern.test(line)) { findings.push({ path: file.path, line: index + 1, kind }); break; }
      }
    }
  }
  return findings;
}

const bytesOf = (text: string): number => new TextEncoder().encode(text).length;

export interface SnapshotCheck {
  readonly files: readonly ArtifactFile[];
  readonly bytes: number;
  readonly problems: readonly string[];
}

/** Validate a whole snapshot before it is published or stored. Sorted, so equal projects hash equal. */
export function checkSnapshot(input: unknown): SnapshotCheck {
  const problems: string[] = [];
  if (!Array.isArray(input)) return { files: [], bytes: 0, problems: ["The project's files are missing."] };
  if (input.length === 0) problems.push("There are no files to publish. Open a project with some code in it first.");
  if (input.length > ARTIFACT_LIMITS.files) problems.push(`An artifact can hold ${ARTIFACT_LIMITS.files} files; this one has ${input.length}.`);
  const seen = new Set<string>();
  const files: ArtifactFile[] = [];
  let bytes = 0;
  for (const entry of input.slice(0, ARTIFACT_LIMITS.files)) {
    const file = entry as Partial<ArtifactFile> | null;
    if (file === null || typeof file !== "object" || typeof file.path !== "string" || typeof file.content !== "string") { problems.push("A file in the snapshot is malformed."); continue; }
    if (!isSafeArtifactPath(file.path)) { problems.push(`${String(file.path).slice(0, 80)} is not a path inside the project.`); continue; }
    const lower = file.path.toLowerCase();
    if (seen.has(lower)) { problems.push(`${file.path} appears twice.`); continue; }
    seen.add(lower);
    const size = bytesOf(file.content);
    if (size > ARTIFACT_LIMITS.fileBytes) { problems.push(`${file.path} is larger than ${ARTIFACT_LIMITS.fileBytes / 1000} KB.`); continue; }
    bytes += size;
    files.push({ path: file.path, content: file.content });
  }
  if (bytes > ARTIFACT_LIMITS.bytes) problems.push(`An artifact can hold ${ARTIFACT_LIMITS.bytes / 1_000_000} MB of text; this one has ${(bytes / 1_000_000).toFixed(1)} MB.`);
  for (const finding of findSecrets(files).slice(0, 5)) problems.push(`${finding.path} line ${finding.line} looks like a ${finding.kind}. Move it into .env (which is never published) before sharing.`);
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return { files, bytes, problems };
}

/** What changed from `base` to `next`, path by path. */
export function diffSnapshots(base: readonly ArtifactFile[], next: readonly ArtifactFile[]): ArtifactChange[] {
  const before = new Map(base.map((file) => [file.path, file.content]));
  const after = new Map(next.map((file) => [file.path, file.content]));
  const changes: ArtifactChange[] = [];
  for (const [path, content] of after) {
    const old = before.get(path);
    if (old === undefined) changes.push({ path, kind: "added", before: null, after: content });
    else if (old !== content) changes.push({ path, kind: "modified", before: old, after: content });
  }
  for (const [path, content] of before) if (!after.has(path)) changes.push({ path, kind: "deleted", before: content, after: null });
  return changes.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** Validate a change set as it arrives from somebody else's machine. */
export function checkChanges(input: unknown): { readonly changes: readonly ArtifactChange[]; readonly problems: readonly string[] } {
  const problems: string[] = [];
  if (!Array.isArray(input) || input.length === 0) return { changes: [], problems: ["An improvement must change at least one file."] };
  if (input.length > ARTIFACT_LIMITS.changes) problems.push(`An improvement can change at most ${ARTIFACT_LIMITS.changes} files.`);
  const changes: ArtifactChange[] = [];
  const seen = new Set<string>();
  let bytes = 0;
  for (const entry of input.slice(0, ARTIFACT_LIMITS.changes)) {
    const change = entry as Partial<ArtifactChange> | null;
    if (change === null || typeof change !== "object" || typeof change.path !== "string" || !isSafeArtifactPath(change.path)) { problems.push("A change names a path outside the project."); continue; }
    if (seen.has(change.path)) { problems.push(`${change.path} is changed twice.`); continue; }
    seen.add(change.path);
    const kind = change.kind;
    const beforeOk = kind === "added" ? change.before === null : typeof change.before === "string";
    const afterOk = kind === "deleted" ? change.after === null : typeof change.after === "string";
    if ((kind !== "added" && kind !== "modified" && kind !== "deleted") || !beforeOk || !afterOk) { problems.push(`The change to ${change.path} is malformed.`); continue; }
    if (kind !== "deleted" && !artifactFileVerdict(change.path, bytesOf(change.after!)).include) { problems.push(`${change.path} cannot be part of an artifact (private, binary, generated or too large).`); continue; }
    bytes += bytesOf(change.after ?? "") + bytesOf(change.before ?? "");
    changes.push({ path: change.path, kind, before: change.before ?? null, after: change.after ?? null });
  }
  if (bytes > ARTIFACT_LIMITS.changeBytes) problems.push(`An improvement can carry ${ARTIFACT_LIMITS.changeBytes / 1_000_000} MB of changes.`);
  const secrets = findSecrets(changes.filter((change) => change.after !== null).map((change) => ({ path: change.path, content: change.after! })));
  for (const finding of secrets.slice(0, 5)) problems.push(`${finding.path} line ${finding.line} looks like a ${finding.kind}. Remove it before sending.`);
  return { changes, problems };
}

export interface ApplyResult {
  readonly files: readonly ArtifactFile[];
  /** Paths whose current content is no longer what the change was made against. */
  readonly conflicts: readonly string[];
  readonly applied: number;
}

/**
 * Apply an improvement to the files as they are now.
 *
 * A change applies cleanly when the file still holds exactly what the contributor started
 * from (or already holds what they ended with - two people making the same fix is not a
 * conflict). Anything else is a conflict and is left alone unless `force` is set, in which
 * case the contributor's version wins: the owner chose "Use theirs" after reading it.
 */
export function applyChanges(current: readonly ArtifactFile[], changes: readonly ArtifactChange[], force = false): ApplyResult {
  const files = new Map(current.map((file) => [file.path, file.content]));
  const conflicts: string[] = [];
  let applied = 0;
  for (const change of changes) {
    const now = files.get(change.path) ?? null;
    if (now === change.after) continue;
    if (now !== change.before && !force) { conflicts.push(change.path); continue; }
    if (change.after === null) files.delete(change.path);
    else files.set(change.path, change.after);
    applied++;
  }
  const result = [...files].map(([path, content]) => ({ path, content })).sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return { files: result, conflicts, applied };
}

export interface DiffLine {
  readonly kind: "same" | "add" | "remove" | "skip";
  readonly text: string;
}

/**
 * A readable line diff for the review screen: changed lines with three lines of context,
 * and long unchanged runs folded into one "skip" row.
 *
 * Longest-common-subsequence on lines, bounded so a 5,000-line rewrite cannot freeze the
 * window: past the bound it reports the whole file as replaced, which is still true.
 */
export function lineDiff(before: string | null, after: string | null, context = 3): DiffLine[] {
  const a = before === null ? [] : before.split("\n");
  const b = after === null ? [] : after.split("\n");
  let start = 0;
  while (start < a.length && start < b.length && a[start] === b[start]) start++;
  let endA = a.length, endB = b.length;
  while (endA > start && endB > start && a[endA - 1] === b[endB - 1]) { endA--; endB--; }
  const midA = a.slice(start, endA), midB = b.slice(start, endB);
  const raw: DiffLine[] = a.slice(0, start).map((text) => ({ kind: "same", text }));
  if (midA.length * midB.length > 4_000_000) {
    raw.push(...midA.map((text): DiffLine => ({ kind: "remove", text })), ...midB.map((text): DiffLine => ({ kind: "add", text })));
  } else {
    const rows = midA.length + 1, cols = midB.length + 1;
    const table = new Uint32Array(rows * cols);
    for (let i = midA.length - 1; i >= 0; i--) {
      for (let j = midB.length - 1; j >= 0; j--) {
        table[i * cols + j] = midA[i] === midB[j] ? table[(i + 1) * cols + j + 1]! + 1 : Math.max(table[(i + 1) * cols + j]!, table[i * cols + j + 1]!);
      }
    }
    let i = 0, j = 0;
    while (i < midA.length || j < midB.length) {
      if (i < midA.length && j < midB.length && midA[i] === midB[j]) { raw.push({ kind: "same", text: midA[i]! }); i++; j++; }
      else if (j < midB.length && (i >= midA.length || table[i * cols + j + 1]! >= table[(i + 1) * cols + j]!)) { raw.push({ kind: "add", text: midB[j]! }); j++; }
      else { raw.push({ kind: "remove", text: midA[i]! }); i++; }
    }
  }
  raw.push(...a.slice(endA).map((text): DiffLine => ({ kind: "same", text })));

  // Fold unchanged runs that are further than `context` lines from any change.
  const keep = raw.map(() => false);
  raw.forEach((line, index) => {
    if (line.kind === "same") return;
    for (let k = Math.max(0, index - context); k <= Math.min(raw.length - 1, index + context); k++) keep[k] = true;
  });
  const folded: DiffLine[] = [];
  let skipped = 0;
  raw.forEach((line, index) => {
    if (keep[index]) {
      if (skipped > 0) { folded.push({ kind: "skip", text: `${skipped} unchanged line${skipped === 1 ? "" : "s"}` }); skipped = 0; }
      folded.push(line);
    } else skipped++;
  });
  if (skipped > 0 && folded.length > 0) folded.push({ kind: "skip", text: `${skipped} unchanged line${skipped === 1 ? "" : "s"}` });
  return folded;
}

/** "+12 −3" for a change, counted from its diff. */
export function changeStats(change: ArtifactChange): { readonly added: number; readonly removed: number } {
  let added = 0, removed = 0;
  for (const line of lineDiff(change.before, change.after, 0)) {
    if (line.kind === "add") added++;
    else if (line.kind === "remove") removed++;
  }
  return { added, removed };
}

/**
 * What a project folder remembers about the artifact it is linked to, in `.adcode/remix.json`.
 *
 * An owner's folder is linked when they publish ("owner"); a remix is linked when it is
 * made ("remix"). Either way the files of the linked version are kept beside it, so
 * "Send improvement" computes exactly what this person changed, and "Get the latest" knows
 * what the newer version changed - even after the artifact has moved on.
 */
export interface RemixRecord {
  readonly artifactId: string;
  readonly title: string;
  readonly version: number;
  readonly remixedAt: number;
  readonly role: "owner" | "remix";
}

export const REMIX_RECORD = ".adcode/remix.json";
export const REMIX_BASE = ".adcode/remix-base.json";

export function parseRemixRecord(text: string): RemixRecord | null {
  try {
    const value = JSON.parse(text) as Partial<RemixRecord>;
    if (typeof value.artifactId !== "string" || !/^[a-z0-9]{12,40}$/.test(value.artifactId)) return null;
    if (typeof value.version !== "number" || !Number.isSafeInteger(value.version) || value.version < 1) return null;
    return { artifactId: value.artifactId, title: typeof value.title === "string" ? value.title.slice(0, 80) : "Remix", version: value.version, remixedAt: typeof value.remixedAt === "number" ? value.remixedAt : 0, role: value.role === "owner" ? "owner" : "remix" };
  } catch {
    return null;
  }
}

/** A folder name for a remix: the title, made safe for every file system. */
export function remixFolderName(title: string): string {
  const safe = title.replace(/[<>:"/\\|?*\u0000-\u001f]/g, " ").replace(/\s+/g, " ").trim().replace(/[. ]+$/, "").slice(0, 60);
  return `${safe || "Artifact"} (remix)`;
}
